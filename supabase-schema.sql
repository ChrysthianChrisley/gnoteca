-- Gatilho de Conexão / Relação de Ideias
create or replace function public.handle_relation_notification()
returns trigger as $$
declare
    target_author_id uuid;
begin
    select author_id into target_author_id from public.knowledge where id = new.source_knowledge_id;
    if target_author_id is not null and target_author_id <> new.user_id then
        insert into public.notifications (user_id, actor_id, type, knowledge_id)
        values (target_author_id, new.user_id, 'relation_' || new.relation_type, new.source_knowledge_id);
    end if;
    return new;
end;
$$ language plpgsql security definer;

drop trigger if exists trigger_notify_relation on public.knowledge_relations;
create trigger trigger_notify_relation
after insert on public.knowledge_relations
for each row
execute function public.handle_relation_notification();

