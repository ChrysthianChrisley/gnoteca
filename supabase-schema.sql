-- 1. Tabela de Perfis Públicos (vinculada ao auth.users)
create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    username text not null unique,
    display_name text not null,
    avatar_url text,
    current_title text not null default 'Explorador de Conhecimento',
    created_at timestamptz not null default now()
);

-- 2. Tabela de Conhecimentos (Átomos de Conhecimento)
create table if not exists public.knowledge (
    id bigint generated by default as identity primary key,
    author_id uuid not null references public.profiles(id) on delete cascade,
    content text not null check (char_length(trim(content)) > 0),
    category text not null,
    tags text[] not null default '{}',
    source text,
    knowledge_type text not null default 'Fato',
    epistemic_status text not null default 'Ideia',
    visibility text not null default 'public',
    parent_id bigint references public.knowledge(id) on delete cascade,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    interactions_count integer not null default 0,
    saved_count integer not null default 0
);

-- 3. Tabela de Interações Semânticas
create table if not exists public.knowledge_interactions (
    id bigint generated by default as identity primary key,
    knowledge_id bigint not null references public.knowledge(id) on delete cascade,
    user_id uuid not null references public.profiles(id) on delete cascade,
    interaction_type text not null, -- 'insight', 'surprising', 'questioned', 'complemented'
    created_at timestamptz not null default now(),
    unique (knowledge_id, user_id, interaction_type)
);

-- 4. Tabela Minha Gnoteca (Salvos)
create table if not exists public.saved_knowledge (
    knowledge_id bigint not null references public.knowledge(id) on delete cascade,
    user_id uuid not null references public.profiles(id) on delete cascade,
    created_at timestamptz not null default now(),
    primary key (knowledge_id, user_id)
);

-- 5. Índices para Alta Performance
create index if not exists knowledge_created_at_idx on public.knowledge (created_at desc);
create index if not exists knowledge_author_id_idx on public.knowledge (author_id);
create index if not exists knowledge_category_idx on public.knowledge (category);
create index if not exists knowledge_parent_id_idx on public.knowledge (parent_id);
create index if not exists interactions_knowledge_id_idx on public.knowledge_interactions (knowledge_id);
create index if not exists saved_knowledge_id_idx on public.saved_knowledge (knowledge_id);

-- 6. Row Level Security (RLS)
alter table public.profiles enable row level security;
alter table public.knowledge enable row level security;
alter table public.knowledge_interactions enable row level security;
alter table public.saved_knowledge enable row level security;

-- Políticas de Acesso para Profiles
drop policy if exists "Profiles are public" on public.profiles;
create policy "Profiles are public" on public.profiles for select using (true);

drop policy if exists "Users can create their profile" on public.profiles;
create policy "Users can create their profile" on public.profiles for insert with check (auth.uid() = id);

drop policy if exists "Users can update their profile" on public.profiles;
create policy "Users can update their profile" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);

-- Políticas de Acesso para Knowledge
drop policy if exists "Knowledge is public" on public.knowledge;
create policy "Knowledge is public" on public.knowledge for select using (visibility = 'public' or auth.uid() = author_id);

drop policy if exists "Authenticated users can create knowledge" on public.knowledge;
create policy "Authenticated users can create knowledge" on public.knowledge for insert to authenticated with check (auth.uid() = author_id);

drop policy if exists "Authors can update knowledge" on public.knowledge;
create policy "Authors can update knowledge" on public.knowledge for update using (auth.uid() = author_id) with check (auth.uid() = author_id);

drop policy if exists "Authors can delete knowledge" on public.knowledge;
create policy "Authors can delete knowledge" on public.knowledge for delete using (auth.uid() = author_id);

-- Políticas de Acesso para Interactions
drop policy if exists "Interactions are public" on public.knowledge_interactions;
create policy "Interactions are public" on public.knowledge_interactions for select using (true);

drop policy if exists "Users manage their interactions" on public.knowledge_interactions;
create policy "Users manage their interactions" on public.knowledge_interactions for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Políticas de Acesso para Saved Knowledge
drop policy if exists "Saved knowledge is private" on public.saved_knowledge;
create policy "Saved knowledge is private" on public.saved_knowledge for select using (auth.uid() = user_id);

drop policy if exists "Users manage their saved knowledge" on public.saved_knowledge;
create policy "Users manage their saved knowledge" on public.saved_knowledge for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- 7. Trigger: Criação Automática de Perfil no Cadastro (incluindo Avatar Google)
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
    insert into public.profiles (id, username, display_name, avatar_url)
    values (
        new.id,
        lower(regexp_replace(coalesce(new.raw_user_meta_data->>'user_name', split_part(new.email, '@', 1)), '[^a-zA-Z0-9]+', '-', 'g')),
        coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', new.email),
        coalesce(new.raw_user_meta_data->>'avatar_url', new.raw_user_meta_data->>'picture')
    )
    on conflict (id) do update set
        avatar_url = coalesce(excluded.avatar_url, profiles.avatar_url),
        display_name = coalesce(excluded.display_name, profiles.display_name);
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

