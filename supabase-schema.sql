-- Tabela de Relações
create table if not exists public.knowledge_relations (
    id bigint generated by default as identity primary key,
    source_knowledge_id bigint not null references public.knowledge(id) on delete cascade,
    target_knowledge_id bigint not null references public.knowledge(id) on delete cascade,
    relation_type text not null default 'related_to', -- 'related_to', 'complements', 'contradicts', etc
    user_id uuid not null references public.profiles(id) on delete cascade,
    created_at timestamptz not null default now(),
    unique (source_knowledge_id, target_knowledge_id, relation_type)
);

create index if not exists knowledge_relations_source_idx on public.knowledge_relations (source_knowledge_id);
create index if not exists knowledge_relations_target_idx on public.knowledge_relations (target_knowledge_id);

alter table public.knowledge_relations enable row level security;
create policy "Knowledge relations are public" on public.knowledge_relations for select using (true);
create policy "Authenticated users can create relations" on public.knowledge_relations for insert to authenticated with check (auth.uid() = user_id);
create policy "Users can delete their relations" on public.knowledge_relations for delete using (auth.uid() = user_id);

-- Tabela de Histórico de Edições
create table if not exists public.knowledge_history (
    id bigint generated by default as identity primary key,
    knowledge_id bigint not null references public.knowledge(id) on delete cascade,
    user_id uuid not null references public.profiles(id) on delete cascade,
    previous_content text not null,
    created_at timestamptz not null default now()
);

create index if not exists knowledge_history_knowledge_idx on public.knowledge_history (knowledge_id);

alter table public.knowledge_history enable row level security;
create policy "Knowledge history is public" on public.knowledge_history for select using (true);
create policy "Authenticated users can create history" on public.knowledge_history for insert to authenticated with check (auth.uid() = user_id);

-- Gatilho de Histórico
create or replace function public.handle_knowledge_history()
returns trigger as $$
begin
    if old.content is distinct from new.content then
        insert into public.knowledge_history (knowledge_id, user_id, previous_content)
        values (old.id, old.author_id, old.content);
    end if;
    return new;
end;
$$ language plpgsql security definer;

drop trigger if exists trigger_knowledge_history on public.knowledge;
create trigger trigger_knowledge_history
before update on public.knowledge
for each row
execute function public.handle_knowledge_history();

