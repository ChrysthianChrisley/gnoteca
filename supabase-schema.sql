drop table if exists public.notifications cascade;

create table if not exists public.notifications (
    id bigint generated always as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    actor_id uuid not null references auth.users(id) on delete cascade,
    type text not null, -- 'interaction', 'saved', 'comment', 'reply'
    knowledge_id bigint references public.knowledge(id) on delete cascade,
    read boolean not null default false,
    created_at timestamptz not null default now()
);

create index if not exists notifications_user_id_idx on public.notifications(user_id, read, created_at desc);
create index if not exists notifications_knowledge_id_idx on public.notifications(knowledge_id);

alter table public.notifications enable row level security;

create policy "Usuários podem ver suas próprias notificações"
on public.notifications for select
using (auth.uid() = user_id);

create policy "Usuários podem atualizar suas próprias notificações"
on public.notifications for update
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "Usuários autenticados podem criar notificações"
on public.notifications for insert
with check (auth.uid() = actor_id);

-- Gatilho de Interação
create or replace function public.handle_interaction_notification()
returns trigger as $$
declare
    target_author_id uuid;
begin
    select author_id into target_author_id from public.knowledge where id = new.knowledge_id;
    if target_author_id is not null and target_author_id <> new.user_id then
        insert into public.notifications (user_id, actor_id, type, knowledge_id)
        values (target_author_id, new.user_id, 'interaction_' || new.interaction_type, new.knowledge_id);
    end if;
    return new;
end;
$$ language plpgsql security definer;

drop trigger if exists trigger_notify_interaction on public.knowledge_interactions;
create trigger trigger_notify_interaction
after insert on public.knowledge_interactions
for each row
execute function public.handle_interaction_notification();

-- Gatilho de Salvar
