-- Função para atualizar contagem de interações
CREATE OR REPLACE FUNCTION public.sync_interaction_counts()
RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE public.knowledge SET interactions_count = interactions_count + 1 WHERE id = NEW.knowledge_id;
    ELSIF TG_OP = 'DELETE' THEN
        UPDATE public.knowledge SET interactions_count = interactions_count - 1 WHERE id = OLD.knowledge_id;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trigger_sync_interaction_counts ON public.knowledge_interactions;
CREATE TRIGGER trigger_sync_interaction_counts
AFTER INSERT OR DELETE ON public.knowledge_interactions
FOR EACH ROW EXECUTE FUNCTION public.sync_interaction_counts();

-- Função para atualizar contagem de salvos
CREATE OR REPLACE FUNCTION public.sync_saved_counts()
RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE public.knowledge SET saved_count = saved_count + 1 WHERE id = NEW.knowledge_id;
    ELSIF TG_OP = 'DELETE' THEN
        UPDATE public.knowledge SET saved_count = saved_count - 1 WHERE id = OLD.knowledge_id;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS trigger_sync_saved_counts ON public.saved_knowledge;
CREATE TRIGGER trigger_sync_saved_counts
AFTER INSERT OR DELETE ON public.saved_knowledge
FOR EACH ROW EXECUTE FUNCTION public.sync_saved_counts();

-- Atualizar updated_at no knowledge
CREATE OR REPLACE FUNCTION public.update_knowledge_updated_at()
RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS update_knowledge_updated_at ON public.knowledge;
CREATE TRIGGER update_knowledge_updated_at
BEFORE UPDATE ON public.knowledge
FOR EACH ROW EXECUTE FUNCTION public.update_knowledge_updated_at();

