export let currentLanguage = localStorage.getItem('gnoteca_language') || 'pt-BR';

export function translate(key) {
    return translations[currentLanguage]?.[key] || translations['pt-BR']?.[key] || key;
}

export function setLanguage(lang) {
    currentLanguage = translations[lang] ? lang : 'pt-BR';
    localStorage.setItem('gnoteca_language', currentLanguage);
    document.documentElement.lang = currentLanguage;
}

// Helper para traduzir tópicos mantendo a chave original no banco
export function getTranslatedTopic(tag) {
    if (!tag) return translate('topicGeneral');
    const topicMap = {
        'Todos': 'topicAll',
        'Ciência': 'topicScience',
        'Filosofia': 'topicPhilosophy',
        'Tecnologia': 'topicTechnology',
        'Neurociência': 'topicNeuroscience',
        'Física': 'topicPhysics',
        'Psicologia': 'topicPsychology',
        'Sociedade': 'topicSociety',
        'Geral': 'topicGeneral'
    };
    const key = topicMap[tag];
    return key ? translate(key) : tag;
}

